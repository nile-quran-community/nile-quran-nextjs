import type { Metadata } from "next";
import { notFound } from "next/navigation";
import { checkTokenValidity } from "@/actions/auth-actions";
import { getAnnouncement, getAnnouncementPreview } from "@/actions/announcements";
import { canEditAnnouncements } from "@/lib/profile-types";
import { AnnouncementArticle, AnnouncementTeaser } from "@/components/News/AnnouncementArticle";

type Props = { params: Promise<{ id: string }> };

function parseId(raw: string): number | null {
  const id = Number(raw);
  return Number.isInteger(id) && id > 0 ? id : null;
}

const noIndex = { index: false, follow: false };

// Built from the public preview only, so it works for a crawler that isn't logged in
// (Discord, WhatsApp) and can never leak the body. The image is generated by ./og/route.tsx;
// it's listed explicitly (a relative URL, resolved against metadataBase) so it's absolute.
export async function generateMetadata({ params }: Props): Promise<Metadata> {
  const id = parseId((await params).id);
  const res = id ? await getAnnouncementPreview(id) : null;
  if (!res?.success) return { title: "إعلان", robots: noIndex };

  const { title, summary, publish_at } = res.data;
  const image = `/news/${id}/og`;
  return {
    title,
    description: summary,
    robots: noIndex,
    openGraph: {
      title,
      description: summary,
      type: "article",
      publishedTime: publish_at,
      locale: "ar_EG",
      siteName: "مقرأة النيل",
      images: [{ url: image, width: 1200, height: 630, alt: title }],
    },
    twitter: { card: "summary_large_image", title, description: summary, images: [image] },
  };
}

export default async function AnnouncementPage({ params }: Props) {
  const id = parseId((await params).id);
  if (!id) notFound();

  const User = await checkTokenValidity();

  if (User.isValid) {
    const res = await getAnnouncement(id);
    if (!res.success) {
      if (res.notFound) notFound();
      throw new Error(res.error);
    }
    return (
      <AnnouncementArticle
        announcement={res.data}
        canEdit={canEditAnnouncements(User.user.groups || [])}
      />
    );
  }

  // Logged out: the teaser, and the body is never even requested
  const res = await getAnnouncementPreview(id);
  if (!res.success) {
    if (res.notFound) notFound();
    throw new Error(res.error);
  }
  return <AnnouncementTeaser announcement={res.data} />;
}
